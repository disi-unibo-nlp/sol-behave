def _ckpt_path(out_contract_dir: Path, k: int) -> Path:
    return out_contract_dir / f"synth_replay_checkpoint_{k}.json"


def _result_path(out_contract_dir: Path, k: int) -> Path:
    return out_contract_dir / f"synth_replay_result_{k}.json"


def _load_ckpt(out_contract_dir: Path, k: int) -> dict:
    p = _ckpt_path(out_contract_dir, k)
    if p.exists():
        try:
            return json.loads(p.read_text())
        except Exception:
            pass
    return {"state": "NOT_STARTED"}


def _save_ckpt(out_contract_dir: Path, k: int, data: dict) -> None:
    _ckpt_path(out_contract_dir, k).write_text(json.dumps(data, indent=2))


