def print_summary(results: list[dict], k: int, threshold: float) -> None:
    done   = [r for r in results if r.get("state") == "DONE"]
    failed = [r for r in results if r.get("state") == "FAILED"]
    passed = [r for r in done if r.get("saved")]

    print("\n" + "═" * 60)
    print(f"  SYNTH REPLAY SUMMARY  (K={k}, threshold={threshold:.0%})")
    print("═" * 60)
    print(f"  Contracts processed : {len(results)}")
    print(f"  Completed (DONE)    : {len(done)}")
    print(f"  Failed              : {len(failed)}")
    print(f"  Passed threshold    : {len(passed)}")

    if done:
        rates = [r["pass_rate"] for r in done if r.get("pass_rate") is not None]
        if rates:
            print(f"  Avg pass rate       : {sum(rates)/len(rates):.1%}")
            print(f"  Min / Max           : {min(rates):.1%} / {max(rates):.1%}")

        ev_counts = [r["n_events_covered"] for r in done
                     if r.get("n_events_covered") is not None]
        if ev_counts:
            print(f"  Avg DCR events covered : {sum(ev_counts)/len(ev_counts):.1f}")

    if failed:
        reasons = Counter(r.get("reason", "?")[:50] for r in failed)
        print(f"\n  Failure reasons:")
        for reason, count in reasons.most_common(8):
            print(f"    {count:>4}× {reason}")
    print("═" * 60)


