def main() -> None:
    args = parse_args()

    for d, label in [(args.dataset, "--dataset"), (args.dcr_dir, "--dcr-dir")]:
        if not d.exists():
            print(f"ERROR: {label} not found: {d}")
            sys.exit(1)

    args.output_dir.mkdir(parents=True, exist_ok=True)

    print(f"""
replay_synth_transactions.py
══════════════════════════════════════════════════════════
  dataset         = {args.dataset}
  dcr_dir         = {args.dcr_dir}
  output_dir      = {args.output_dir}
  work_dir        = {args.work_dir}
  k               = {args.k}
  pass_threshold  = {args.pass_threshold:.0%}
  tx_timeout      = {args.tx_timeout}s
  force           = {args.force}
  retry_failed    = {args.retry_failed}
  results_file    = {args.results_file}
══════════════════════════════════════════════════════════
""")

    # Discover: contracts that have both metadata (dataset) AND synthetic txs (dcr_dir)
    if args.addresses:
        requested = {a.lower() for a in args.addresses}
        contract_dirs = sorted([
            args.dcr_dir / addr for addr in requested
            if (args.dcr_dir / addr).exists()
            and (args.dataset / addr).exists()
        ])
    else:
        contract_dirs = sorted([
            d for d in args.dcr_dir.iterdir()
            if d.is_dir()
            and (d / "transactions_synthetic.json").exists()
            and (args.dataset / d.name).exists()
        ])

    if not contract_dirs:
        print("No contracts with synthetic transactions found. "
              "Run make_sequences_hardhat.py first.")
        sys.exit(0)

    print(f"Found {len(contract_dirs)} contract(s) with synthetic transactions.\n")

    setup_workspace(args.work_dir)

    all_results: list[dict] = []
    start_time = time.time()

    try:
        for i, dcr_contract_dir in enumerate(contract_dirs, 1):
            address = dcr_contract_dir.name
            print(f"[{i}/{len(contract_dirs)}] {address}")
            try:
                result = replay_synth_contract(
                    address        = address,
                    dataset_dir    = args.dataset,
                    dcr_dir        = args.dcr_dir,
                    output_dir     = args.output_dir,
                    work_dir       = args.work_dir,
                    k              = args.k,
                    pass_threshold = args.pass_threshold,
                    tx_timeout     = args.tx_timeout,
                    force          = args.force,
                    retry_failed   = args.retry_failed,
                    verbose        = args.verbose,
                )
                all_results.append(result)
            except KeyboardInterrupt:
                raise
            except Exception as e:
                print(f"  Unexpected error: {e}")
                all_results.append({
                    "state": "FAILED", "address": address,
                    "reason": f"unexpected error: {e}",
                })
    except KeyboardInterrupt:
        print("\nInterrupted — saving partial results ...")

    elapsed = time.time() - start_time
    args.results_file.write_text(json.dumps({
        "timestamp":        datetime.utcnow().isoformat(),
        "duration_seconds": round(elapsed, 1),
        "config": {
            "k": args.k, "pass_threshold": args.pass_threshold,
            "dataset": str(args.dataset), "dcr_dir": str(args.dcr_dir),
        },
        "total":   len(all_results),
        "done":    sum(1 for r in all_results if r.get("state") == "DONE"),
        "failed":  sum(1 for r in all_results if r.get("state") == "FAILED"),
        "passed":  sum(1 for r in all_results if r.get("saved")),
        "results": all_results,
    }, indent=2))
    print(f"\nResults written to {args.results_file}")

    print_summary(all_results, args.k, args.pass_threshold)
    print(f"\n  Total time: {_format_elapsed(elapsed)}")


if __name__ == "__main__":
    main()