"""
replay_synth_transactions.py
============================

Replay synthetic transactions (generated by make_sequences_hardhat.py via
DCR graph exploration) against the original contracts.

Unlike replay_transactions.py which uses historical Etherscan transactions,
this script uses the pre-validated synthetic transactions from:
  <dcr_dir>/<address>/transactions_synthetic.json

Key differences from replay_transactions.py
--------------------------------------------
1. Transaction source: transactions_synthetic.json instead of transactions.json
2. Constructor args:   loaded from deploy_params.json (synthesized by hardhat_server.py
   during DCR generation) instead of the Etherscan/decode/default chain.
3. No filtering:       synthetic txs are already validated — no isError or
   deploy_block filtering needed. All are directed to the contract with calldata.
4. Expected status:    all synthetic txs have txreceipt_status="1" (they ran
   successfully during generation). A replay that fails is a real divergence.
5. Extra metadata:     per-tx _event_id, _branch_guard, _fn_sig, _decoded_params
   are preserved in the result for coverage analysis.

Since synthetic transactions are DCR-guided they provide much better function
coverage than historical transactions — comparing pass rates between the two
replay modes reveals which functions are exercised by real users vs which
branches are only reachable via specific call sequences.

Directory layout
----------------
  <dataset_dir>/
    <address>/
      abi.json
      metadata.json
      source.json | source.sol
      deploy_params.json      ← constructor args cached by hardhat_server.py

  <dcr_dir>/
    <address>/
      transactions_synthetic.json   ← generated by make_sequences_hardhat.py

  <output_dir>/              ← written by this script
    <address>/
      synth_replay_checkpoint_<K>.json
      synth_replay_result_<K>.json

Usage
-----
  python replay_synth_transactions.py [options]

  # Default paths:
  python replay_synth_transactions.py

  # Custom paths:
  python3 replay_synth_transactions.py \
      --dataset   ../dataset/contracts_dataset_1to20 \
      --dcr-dir   ../dcr_generation/generated_dcr_1to20 \
      --output-dir ./synth_replay_results \
      --k 1000 \
      --verbose | tee original_synth.log

  # Only specific contracts:
  python replay_synth_transactions.py --addresses 0xabc... 0xdef...

  # Force re-run:
  python replay_synth_transactions.py --force
"""

