def load_synth_data(
    dataset_dir: Path,
    dcr_dir:     Path,
    address:     str,
) -> Optional[dict]:
    """
    Load all data needed to replay synthetic transactions for one contract.

    Returns a dict with:
      meta, abi, source_path, source_data, transactions, constructor_args
    Returns None if any required file is missing.
    """
    original_dir = dataset_dir / address
    dcr_addr_dir = dcr_dir / address

    # ── metadata.json (from dataset) ────────────────────────────────────
    meta_path = original_dir / "metadata.json"
    if not meta_path.exists():
        return None
    try:
        meta = json.loads(meta_path.read_text())
    except Exception:
        return None

    # ── abi.json (from dataset) ──────────────────────────────────────────
    abi: list = []
    abi_path = original_dir / "abi.json"
    if abi_path.exists():
        try:
            abi = json.loads(abi_path.read_text())
        except Exception:
            pass

    # ── source (from dataset) ────────────────────────────────────────────
    source_path = original_dir / "source.json"
    if not source_path.exists():
        source_path = original_dir / "source.sol"
    if not source_path.exists():
        return None

    # ── constructor args from deploy_params.json ─────────────────────────
    # deploy_params.json is written by hardhat_server.py during DCR generation.
    # It contains the exact args used to deploy the contract, which are the
    # canonical args for this evaluation.  Fall back to ABI defaults if absent.
    constructor_args: list = []
    deploy_params_path = original_dir / "deploy_params.json"
    if deploy_params_path.exists():
        try:
            dp = json.loads(deploy_params_path.read_text())
            if dp.get("constructor_args") is not None and not dp.get("deploy_failed"):
                constructor_args = dp["constructor_args"]
        except Exception:
            pass
    if not constructor_args:
        ctor = next((e for e in abi if e.get("type") == "constructor"), None)
        constructor_args = _default_args(ctor.get("inputs", []) if ctor else [])

    # ── transactions_synthetic.json (from dcr_dir) ───────────────────────
    synth_path = dcr_addr_dir / "transactions_synthetic.json"
    if not synth_path.exists():
        return None
    try:
        transactions = json.loads(synth_path.read_text())
    except Exception:
        return None

    return {
        "address":          address,
        "meta":             meta,
        "abi":              abi,
        "source_path":      source_path,
        "source_data":      {},   # not needed — constructor args from deploy_params
        "transactions":     transactions,
        "constructor_args": constructor_args,
    }


def filter_synth_txs(txs: list, address: str, k: int) -> list:
    """
    Filter synthetic transactions for replay.

    Synthetic txs are already validated (all succeeded during generation),
    so we only need to check:
      - directed to the contract address
      - have calldata
    No isError or deploy_block filtering needed.
    """
    addr_lower = address.lower()
    result = []
    for tx in txs:
        if (tx.get("to") or "").lower() != addr_lower:
            continue
        if tx.get("input", "0x") in ("0x", ""):
            continue
        result.append(tx)
    return result[:k]


