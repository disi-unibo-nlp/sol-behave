def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Replay synthetic DCR transactions against original contracts.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    p.add_argument("--dataset",    type=Path, default=Path(DEFAULT_DATASET))
    p.add_argument("--dcr-dir",    type=Path, default=Path(DEFAULT_DCR_DIR),
                   dest="dcr_dir",
                   help="DCR generation output dir (contains transactions_synthetic.json).")
    p.add_argument("--output-dir", type=Path, default=Path(DEFAULT_OUTPUT),
                   dest="output_dir",
                   help="Where to write synth replay checkpoints and results.")
    p.add_argument("--work-dir",   type=Path, default=Path(DEFAULT_WORK_DIR),
                   dest="work_dir")
    p.add_argument("--k",          type=int,  default=DEFAULT_K)
    p.add_argument("--pass-threshold", type=float, default=DEFAULT_THRESHOLD,
                   dest="pass_threshold")
    p.add_argument("--tx-timeout", type=int,  default=DEFAULT_TX_TIMEOUT,
                   dest="tx_timeout")
    p.add_argument("--addresses",  nargs="*", metavar="ADDR")
    p.add_argument("--force",      action="store_true")
    p.add_argument("--retry-failed", action="store_true", dest="retry_failed")
    p.add_argument("--verbose", "-v", action="store_true")
    p.add_argument("--results-file", type=Path,
                   default=_SCRIPT_DIR / "synth_replay_results.json",
                   dest="results_file")
    return p.parse_args()


