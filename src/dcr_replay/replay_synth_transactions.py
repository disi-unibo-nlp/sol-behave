def replay_synth_contract(
    address:      str,
    dataset_dir:  Path,
    dcr_dir:      Path,
    output_dir:   Path,
    work_dir:     Path,
    k:            int,
    pass_threshold: float,
    tx_timeout:   int,
    force:        bool = False,
    retry_failed: bool = False,
    verbose:      bool = False,
) -> dict:
    """
    Compile, deploy, and replay up to K synthetic transactions for one contract.
    """
    out_contract_dir = output_dir / address
    out_contract_dir.mkdir(parents=True, exist_ok=True)

    # Checkpoint
    ckpt = _load_ckpt(out_contract_dir, k)
    state = ckpt.get("state")
    if state in ("DONE", "FAILED"):
        if force or (retry_failed and state == "FAILED"):
            pass
        else:
            if verbose:
                print(f"  Already {state} — skipping")
            return ckpt

    # Load data
    data = load_synth_data(dataset_dir, dcr_dir, address)
    if data is None:
        result = {
            "state":   "FAILED",
            "address": address,
            "reason":  "missing required files (metadata/source/transactions_synthetic)",
        }
        _save_ckpt(out_contract_dir, k, result)
        return result

    meta              = data["meta"]
    abi               = data["abi"]
    source_path       = data["source_path"]
    transactions      = data["transactions"]
    constructor_args  = data["constructor_args"]
    contract_name     = meta.get("contract_name", "Contract")

    if meta.get("is_proxy"):
        result = {"state": "FAILED", "address": address, "reason": "proxy — skipped"}
        _save_ckpt(out_contract_dir, k, result)
        return result

    txs_to_replay = filter_synth_txs(transactions, address, k)
    if not txs_to_replay:
        result = {
            "state":   "FAILED",
            "address": address,
            "reason":  "no synthetic transactions found",
        }
        _save_ckpt(out_contract_dir, k, result)
        return result

    view_selectors = build_view_selectors(abi)
    print(f"  {contract_name} ({address[:12]}…)  |  "
          f"synth_txs={len(txs_to_replay)}  view_fns={len(view_selectors)}")

    # ── Step 1: Compile ───────────────────────────────────────────────────
    print(f"  Compiling ...", end="  ", flush=True)
    ok, err = prepare_and_compile(source_path, meta, work_dir)
    if not ok:
        print("✗")
        if verbose:
            print(f"    {err[-400:]}")
        result = {
            "state": "FAILED", "address": address,
            "reason": "compilation failed", "stderr": err[-300:],
        }
        _save_ckpt(out_contract_dir, k, result)
        return result
    print("✓")
    _save_ckpt(out_contract_dir, k, {"state": "COMPILED", "address": address})

    if verbose and constructor_args:
        print(f"  Constructor args (deploy_params): {constructor_args}")

    # Build FQN
    if source_path.suffix == ".sol":
        fqn = f"contracts/{source_path.name}:{contract_name}"
    else:
        sources_map = json.loads(source_path.read_text()).get("sources", {})
        first_file  = next(iter(sources_map), None)
        fqn = f"contracts/{first_file}:{contract_name}" if first_file else contract_name

    # ── Step 2: Deploy ────────────────────────────────────────────────────
    server = DeployServer(work_dir, tx_timeout=tx_timeout)
    try:
        print(f"  Deploying {fqn} ...", end="  ", flush=True)
        try:
            deployed_address = server.deploy(fqn, constructor_args,
                                             view_selectors=view_selectors)
        except RuntimeError as e:
            print(f"✗  {e}")
            ctor_entry = next((e for e in abi if e.get("type") == "constructor"), None)
            fallback   = _default_args(ctor_entry.get("inputs", []) if ctor_entry else [])
            if fallback != constructor_args:
                print(f"  Retrying with zero defaults ...", end="  ", flush=True)
                try:
                    deployed_address = server.deploy(fqn, fallback,
                                                     view_selectors=view_selectors)
                    constructor_args = fallback
                except RuntimeError as e2:
                    print(f"✗  {e2}")
                    server.close()
                    result = {"state": "FAILED", "address": address,
                              "reason": f"deploy failed: {e2}"}
                    _save_ckpt(out_contract_dir, k, result)
                    return result
            else:
                server.close()
                result = {"state": "FAILED", "address": address,
                          "reason": f"deploy failed: {e}"}
                _save_ckpt(out_contract_dir, k, result)
                return result

        print(f"✓  {deployed_address[:14]}…")
        _save_ckpt(out_contract_dir, k, {
            "state": "DEPLOYED", "address": address,
            "deployed_address": deployed_address,
            "constructor_args": constructor_args,
        })

        # ── Step 3: Replay ─────────────────────────────────────────────────
        print(f"  Replaying {len(txs_to_replay)} synthetic txs ...")
        tx_results = []
        passed = 0
        failed = 0

        _iter = tqdm(enumerate(txs_to_replay, 1), total=len(txs_to_replay), unit="tx", desc="replay") if HAS_TQDM else enumerate(txs_to_replay, 1)
        for i, tx in _iter:
            tx_hash = tx.get("hash", "")
            try:
                res   = server.replay_tx(tx)
                match = res.get("events_match", False)
                # Capture view-function state after every tx (both pass and fail)
                # so divergence analysis can compare original vs generated state.
                if i % 50 == 0 or i == len(txs_to_replay):
                    res["_view_state"] = _read_view_state(server, view_selectors)
                    if HAS_TQDM and isinstance(_iter, tqdm):
                        _iter.write(f"    snapshot saved at tx {i}/{len(txs_to_replay)}")
                    else:
                        print(f"    snapshot saved at tx {i}/{len(txs_to_replay)}", flush=True)
                if match:
                    passed += 1
                else:
                    failed += 1
                    if verbose:
                        reason = (res.get("revert_reason") or res.get("error") or "")[:100]
                        event_id = tx.get("_event_id", "")
                        guard    = tx.get("_branch_guard", "")
                        print(f"    tx {i} [{event_id}] mismatch: {reason}"
                              + (f"  guard={guard!r}" if guard else ""))

                # Preserve DCR metadata in the result entry
                res["_event_id"]       = tx.get("_event_id", "")
                res["_branch_guard"]   = tx.get("_branch_guard", "")
                res["_fn_sig"]         = tx.get("_fn_sig", "")
                res["_param_source"]   = tx.get("_param_source", "")
                res["_decoded_params"] = tx.get("_decoded_params", {})
                tx_results.append(res)

            except TimeoutError:
                failed += 1
                tx_results.append({
                    "hash": tx_hash, "actual_status": "timeout",
                    "events_match": False,
                    "_event_id": tx.get("_event_id", ""),
                    "_fn_sig":   tx.get("_fn_sig", ""),
                })
            except Exception as e:
                failed += 1
                tx_results.append({
                    "hash": tx_hash, "actual_status": "error",
                    "events_match": False, "error": str(e),
                    "_event_id": tx.get("_event_id", ""),
                    "_fn_sig":   tx.get("_fn_sig", ""),
                })

            if HAS_TQDM and isinstance(_iter, tqdm):
                _iter.set_postfix(pass_rate=f"{passed/i:.1%}", passed=passed, failed=failed)
            elif i % 50 == 0 or i == len(txs_to_replay):
                print(f"    [{i:>5}/{len(txs_to_replay)}]  "
                      f"pass={passed}  fail={failed}  rate={passed/i:.1%}")

        # ── Step 4: Summarise ──────────────────────────────────────────────
        total     = len(txs_to_replay)
        pass_rate = round(passed / total, 4) if total else None
        saved     = pass_rate is not None and pass_rate >= pass_threshold

        # Per-function pass rates from _fn_sig metadata
        fn_pass: dict[str, list[bool]] = {}
        for r in tx_results:
            fn_sig = r.get("_fn_sig", "").split("(")[0]
            if fn_sig:
                fn_pass.setdefault(fn_sig, []).append(r.get("events_match", False))
        fn_pass_rates = {
            fn: round(sum(v) / len(v), 4) for fn, v in fn_pass.items()
        }

        # Event/branch coverage
        events_covered   = {r["_event_id"] for r in tx_results if r.get("_event_id")}
        branches_covered = {r["_branch_guard"] for r in tx_results
                            if r.get("_branch_guard")}

        gas_ratios = [r["gas_ratio"] for r in tx_results
                      if r.get("gas_ratio") is not None]

        result = {
            "state":            "DONE",
            "address":          address,
            "contract_name":    contract_name,
            "deployed_address": deployed_address,
            "constructor_args": constructor_args,
            "k":                total,
            "passed":           passed,
            "failed":           failed,
            "pass_rate":        pass_rate,
            "saved":            saved,
            "fn_pass_rates":    fn_pass_rates,
            "n_events_covered": len(events_covered),
            "n_branches_covered": len(branches_covered),
            "mean_gas_ratio":   round(sum(gas_ratios) / len(gas_ratios), 4)
                                if gas_ratios else None,
        }
        _save_ckpt(out_contract_dir, k, result)

        _result_path(out_contract_dir, k).write_text(json.dumps({
            **result,
            "timestamp":  datetime.utcnow().isoformat(),
            "tx_results": tx_results,
        }, indent=2))

        icon = "✓ PASS" if saved else "✗ FAIL"
        rate_str = f"{pass_rate:.1%}" if pass_rate is not None else "n/a"
        print(f"  → {icon}  pass_rate={rate_str}  ({passed}/{total})\n")
        return result

    finally:
        server.close()


